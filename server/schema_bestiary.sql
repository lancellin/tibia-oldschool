CREATE TABLE IF NOT EXISTS `bestiary_monsters` (
  `creature_id` smallint unsigned NOT NULL,
  `name` varchar(100) NOT NULL,
  `kills_stage_1` smallint unsigned NOT NULL DEFAULT '100',
  `kills_stage_2` smallint unsigned NOT NULL DEFAULT '1000',
  `kills_stage_3` smallint unsigned NOT NULL DEFAULT '2500',
  `charm_points` smallint unsigned NOT NULL DEFAULT '0',
  `enabled` tinyint NOT NULL DEFAULT '1',
  PRIMARY KEY (`creature_id`),
  UNIQUE KEY `uk_bestiary_monsters_name` (`name`)
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8;

CREATE TABLE IF NOT EXISTS `player_bestiary_progress` (
  `player_id` int NOT NULL,
  `creature_id` smallint unsigned NOT NULL,
  `kills` int unsigned NOT NULL DEFAULT '0',
  `last_stage_reached` tinyint unsigned NOT NULL DEFAULT '0',
  `created_at` bigint unsigned NOT NULL DEFAULT '0',
  `updated_at` bigint unsigned NOT NULL DEFAULT '0',
  PRIMARY KEY (`player_id`, `creature_id`),
  KEY `idx_player_bestiary_progress_creature_id` (`creature_id`),
  FOREIGN KEY (`player_id`) REFERENCES `players`(`id`) ON DELETE CASCADE,
  FOREIGN KEY (`creature_id`) REFERENCES `bestiary_monsters`(`creature_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8;

CREATE TABLE IF NOT EXISTS `player_charms` (
  `player_id` int NOT NULL,
  `charm_id` tinyint unsigned NOT NULL,
  `state` tinyint unsigned NOT NULL DEFAULT '0',
  `updated_at` bigint unsigned NOT NULL DEFAULT '0',
  PRIMARY KEY (`player_id`, `charm_id`),
  CONSTRAINT `fk_player_charms_player`
    FOREIGN KEY (`player_id`) REFERENCES `players` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARACTER SET=utf8;

